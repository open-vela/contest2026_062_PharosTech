#define RK3576_UART0_ADDR      0x2AD40000
#define RK3576_UART1_ADDR      0x27310000
#define RK3576_UART2_ADDR      0x2AD50000
#define RK3576_UART3_ADDR      0x2AD60000
#define RK3576_UART4_ADDR      0x2AD70000

