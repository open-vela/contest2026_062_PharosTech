"""Derive AMP and headless profiles from the ordinary product defconfig."""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
AMP = {
    'SMP': 'y', 'SMP_NCPUS': '4', 'SMP_DEFAULT_CPUSET': '0xf',
    'PM_NDOMAINS': '5',
    'ARM64_GICV2_PREINITIALIZED': 'y', 'ARM64_GICV2_STATIC_SPI': 'y',
    'RAM_START': '0x4a400000', 'RAM_SIZE': '16777216',
    'RK3576_RAMBANK2_ADDR': '0x70000000', 'RK3576_RAMBANK2_SIZE_MB': '256',
    'RK3576_RPTUN': 'y', 'RK3576_SHMEM': 'y', 'DEV_SIMPLE_ADDRENV': 'y',
    'RPTUN': 'y', 'RPMSG_CHAR': 'y', 'OPENAMP_CACHE': 'y',
    'EXAMPLES_NYAMPCTL': 'y', 'NYABULA_CORE_COMPUTE': 'y',
    'NYABULA_CORE_VOICE': 'y', 'NYABULA_CORE_VOICE_CODEC_HALF': 'y',
    # Phone interoperability has not been accepted; do not silently turn on
    # the Bluetooth audio experiment in a reproducible product profile.
    'NYABULA_CORE_BT': 'n', 'SV6621_BT_SCO': 'n',
}



def derive(base, changes):
    lines = []
    for line in base.splitlines():
        match = re.match(r'(?:CONFIG_|# CONFIG_)(\w+)(?:=| is not set)', line)
        if match and match[1] in changes:
            continue
        lines.append(line)
    for key, value in changes.items():
        lines.append(f'# CONFIG_{key} is not set' if value == 'n'
                     else f'CONFIG_{key}={value}')
    return '# Generated by tools/generate_product_profiles.py; edit the source profiles.\n' + '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    base = (ROOT / 'configs/product/defconfig').read_text(encoding='utf-8')
    for name, changes in [('product_amp', AMP)]:
        path = ROOT / 'configs' / name / 'defconfig'
        expected = derive(base, changes)
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != expected:
                raise SystemExit(f'{path}: regenerate product profiles')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
